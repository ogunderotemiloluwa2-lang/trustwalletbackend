#!/usr/bin/env node
/**
 * Interactive MongoDB setup for Trust Wallet Web.
 *
 * Prompts for the Atlas connection string, generates a JWT secret, verifies the
 * connection actually works, and writes the result to .env. Secrets are typed
 * locally and never leave this machine.
 *
 * Usage:
 *   npm run setup:db
 *   npm run setup:db -- --uri "mongodb+srv://..."   # skip the prompt
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const readline = require('node:readline');

const ENV_PATH = path.join(__dirname, '..', '.env');
const ENV_EXAMPLE_PATH = path.join(__dirname, '..', '.env.example');

const args = process.argv.slice(2);
const flagValue = (name) => {
  const index = args.indexOf(name);
  return index === -1 ? undefined : args[index + 1];
};

const readEnvFile = (filePath) => {
  if (!fs.existsSync(filePath)) return {};
  return fs
    .readFileSync(filePath, 'utf8')
    .split('\n')
    .reduce((acc, line) => {
      const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
      if (match) acc[match[1]] = match[2].replace(/^["']|["']$/g, '');
      return acc;
    }, {});
};

const prompt = (question, { hidden = false } = {}) =>
  new Promise((resolve) => {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true });
    if (!hidden) {
      rl.question(question, (answer) => {
        rl.close();
        resolve(answer.trim());
      });
      return;
    }
    // Mute the echo so the connection string is not printed to the terminal.
    const onData = (char) => {
      if (['\n', '\r', '\u0004'].includes(char.toString())) return;
      process.stdout.write('\r\x1b[K' + question);
    };
    process.stdin.on('data', onData);
    rl.question(question, (answer) => {
      process.stdin.removeListener('data', onData);
      process.stdout.write('\n');
      rl.close();
      resolve(answer.trim());
    });
  });

const generateSecret = () => crypto.randomBytes(48).toString('base64url');

const PASSWORD_PLACEHOLDER = /<db_password>|<password>|<PASSWORD>|<pass>/;

// Adds a database name when the URI has none, so data does not land in the
// shared "test" database. Searches for the path after the last "@" so a "/" or
// "?" inside the password cannot be mistaken for the start of the path.
const ensureDatabaseName = (uri, fallback) => {
  const [base, query] = uri.split('?');
  const suffix = query ? `?${query}` : '';
  const authorityEnd = base.lastIndexOf('@');
  const searchFrom = authorityEnd === -1 ? base.indexOf('://') + 3 : authorityEnd;
  const pathStart = base.indexOf('/', searchFrom);
  if (pathStart === -1) return `${base}/${fallback}${suffix}`;
  if (base.slice(pathStart + 1)) return uri;
  return `${base}${fallback}${suffix}`;
};

const writeEnvFile = (values) => {
  const lines = [
    '# Generated by `npm run setup:db`. Do not commit this file.',
    `MONGODB_URI=${values.MONGODB_URI}`,
    `JWT_SECRET=${values.JWT_SECRET}`,
    `API_PORT=${values.PORT}`,
    'CORS_ORIGIN=http://localhost:3000',
    '',
  ];
  fs.writeFileSync(ENV_PATH, lines.join('\n'), { mode: 0o600 });
};

const verifyConnection = async (uri) => {
  const mongoose = require('mongoose');
  await mongoose.connect(uri, { serverSelectionTimeoutMS: 10000 });
  const { host, name } = mongoose.connection;
  await mongoose.connection.db.admin().ping();
  await mongoose.disconnect();
  return { host, name };
};

const main = async () => {
  console.log('\nTrust Wallet Web — MongoDB setup\n');

  const existing = readEnvFile(ENV_PATH);
  const example = readEnvFile(ENV_EXAMPLE_PATH);

  let uri = flagValue('--uri') || process.env.MONGODB_URI || '';

  if (!uri) {
    console.log('Paste your MongoDB connection string. It is hidden as you type.');
    console.log('Atlas: Cluster -> Connect -> Drivers -> copy the mongodb+srv:// string.');
    console.log('Local: mongodb://127.0.0.1:27017/trustwallet\n');
    uri = await prompt('MONGODB_URI: ', { hidden: true });
  }

  if (!uri) {
    console.error('\nNo connection string provided. Nothing was written.');
    process.exit(1);
  }
  if (!/^mongodb(\+srv)?:\/\//.test(uri)) {
    console.error('\nThat does not look like a MongoDB URI (it must start with mongodb:// or mongodb+srv://).');
    process.exit(1);
  }

  if (PASSWORD_PLACEHOLDER.test(uri)) {
    console.log('\nThe connection string still contains a password placeholder.');
    console.log('Paste the password for your Atlas database user. It is hidden as you type.');
    console.log('If it contains @ : / ? # [ ] then URL-encode it (for example @ becomes %40).\n');
    const password = await prompt('Database user password: ', { hidden: true });
    if (!password) {
      console.error('\nNo password provided. Nothing was written.');
      process.exit(1);
    }
    uri = uri.replace(PASSWORD_PLACEHOLDER, encodeURIComponent(password));
  }

  uri = ensureDatabaseName(uri, 'trustwallet');

  const secret = existing.JWT_SECRET && existing.JWT_SECRET.length >= 32 ? existing.JWT_SECRET : generateSecret();
  const port = existing.API_PORT || example.API_PORT || '5000';

  console.log('\nVerifying the connection...');
  try {
    const { host, name } = await verifyConnection(uri);
    console.log(`Connected to ${host} (database: ${name || 'default'}).`);
  } catch (error) {
    console.error(`\nCould not connect: ${error.message}`);
    console.error('\nCommon causes:');
    console.error('  - The database user password contains @ : / ? # [ ] and is not URL-encoded.');
    console.error('  - Your current IP is not in Atlas -> Network Access.');
    console.error('  - The database user does not exist in Atlas -> Database Access.');
    console.error('\nNothing was written to .env.');
    process.exit(1);
  }

  writeEnvFile({ MONGODB_URI: uri, JWT_SECRET: secret, PORT: port });

  console.log(`\nWrote ${ENV_PATH}`);
  console.log(`  MONGODB_URI  ${uri.replace(/\/\/[^@]*@/, '//<credentials>@')}`);
  console.log(`  JWT_SECRET   ${secret.length} characters (generated)`);
  console.log(`  API_PORT     ${port}`);
  console.log('\nNext: npm run dev   (then npm start in the frontend folder)\n');
};

main().catch((error) => {
  console.error('\nSetup failed:', error.message);
  process.exit(1);
});
